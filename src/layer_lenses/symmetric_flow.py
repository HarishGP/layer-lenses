"""Symmetrised gradients for the designed two-hidden-layer inits: the orbit structure of the tree-flip / label-negation group on the
parameter coordinates, and the projection of a gradient onto the symmetric subspace (average over each orbit with signs; orbits that
contain a coordinate and its negative are set to zero).

Coordinates: W1 is represented by its 62 x 61 coefficients in the orthonormal basis [u_0..u_30 ; o_0..o_29] (the 31 ODT normals and the
30 probes' initial off-span directions, in HIERARCHY_TARGETS order); W2 is 60 x 62; Wout is 60. Rows and units carry the design identities
(probe p <-> HIERARCHY_TARGETS[p]; cue row <-> (leaf, pole); unit <-> (node, block sign, path sign)).
"""
from __future__ import annotations

import numpy as np

from layer_lenses.designed_init import HIERARCHY_TARGETS, node_ancestors


def mirror(j: int, k: int) -> int:
    """Image of node k under the flip at node j (the two subtrees below j exchanged; j and nodes outside its subtree fixed)."""
    if k == j or j not in node_ancestors(k):
        return k
    path = []
    c = k
    while c != j:
        path.append((c - 1) % 2)
        c = (c - 1) // 2
    c = j
    first = True
    for d in reversed(path):
        c = 2 * c + 1 + ((1 - d) if first else d)
        first = False
    return c


def symmetric_orbits(cue_identity: dict, unit_identity: list) -> dict:
    """Orbit index and sign of every parameter coordinate under the group generated by the 15 flips and the label negation.

    cue_identity: {(leaf, pole): row}; unit_identity: list of (node, block_sign, path_sign) per unit. Returns arrays ``orbit`` and
    ``sign`` (and ``forced_zero`` per orbit) for the blocks "W1" (62 x 61 coefficients), "W2" (60 x 62) and "Wout" (60), plus the
    number of free orbits.
    """
    probes = {HIERARCHY_TARGETS[p]: p for p in range(30)}
    row_id = {p: HIERARCHY_TARGETS[p] for p in range(30)}
    row_id.update({r: k for k, r in cue_identity.items()})
    row_of = {v: k for k, v in row_id.items()}
    unit_of = {tuple(u): i for i, u in enumerate(unit_identity)}
    n_rows, n_units = 62, len(unit_identity)
    comps = list(range(31)) + [("off", p) for p in range(30)]
    coords = [("W1", r, k) for r in range(n_rows) for k in range(61)] + [("W2", u, r) for u in range(n_units) for r in range(n_rows)] + [("Wout", u) for u in range(n_units)]
    idx = {c: i for i, c in enumerate(coords)}

    def row_map_flip(j, r):
        n, p = row_id[r]
        return row_of[(mirror(j, n), -p if n == j else p)]

    def comp_map_flip(j, k):
        if k >= 31:
            return 31 + row_map_flip(j, k - 31), 1
        return mirror(j, k), (-1 if k == j else 1)

    def unit_map_flip(j, u):
        n, b, s = unit_identity[u]
        return unit_of[(mirror(j, n), -b if n == j else b, s)]

    def row_map_neg(r):
        n, p = row_id[r]
        return row_of[(n, -p)] if n >= 15 else r

    def unit_map_neg(u):
        n, b, s = unit_identity[u]
        return unit_of[(n, -b, -s)]

    gens = []
    for j in range(15):
        g = {}
        for c in coords:
            if c[0] == "W1":
                k2, sg = comp_map_flip(j, c[2]); g[c] = (("W1", row_map_flip(j, c[1]), k2), sg)
            elif c[0] == "W2":
                g[c] = (("W2", unit_map_flip(j, c[1]), row_map_flip(j, c[2])), 1)
            else:
                g[c] = (("Wout", unit_map_flip(j, c[1])), 1)
        gens.append(g)
    g = {}
    for c in coords:
        if c[0] == "W1":
            g[c] = (("W1", row_map_neg(c[1]), c[2]), -1 if (c[2] < 31 and c[2] >= 15) else 1)
        elif c[0] == "W2":
            g[c] = (("W2", unit_map_neg(c[1]), row_map_neg(c[2])), 1)
        else:
            g[c] = (("Wout", unit_map_neg(c[1])), -1)
    gens.append(g)
    parent = list(range(len(coords))); sign = [1] * len(coords); bad = set()

    def find(i):
        if parent[i] == i:
            return i, 1
        r, s = find(parent[i]); parent[i], sign[i] = r, s * sign[i]
        return r, sign[i]

    def union(i, j, s):
        ri, si = find(i); rj, sj = find(j)
        if ri == rj:
            if si * s != sj:
                bad.add(ri)
            return
        parent[rj] = ri; sign[rj] = si * s * sj

    for gmap in gens:
        for c, (c2, s) in gmap.items():
            union(idx[c], idx[c2], s)
    roots = {}
    orbit = np.zeros(len(coords), dtype=np.int64); sgn = np.zeros(len(coords), dtype=np.float64)
    for i in range(len(coords)):
        r, s = find(i); orbit[i] = roots.setdefault(r, len(roots)); sgn[i] = s
    forced = np.zeros(len(roots), dtype=bool)
    for r in bad:                                   # a root recorded as contradictory may have been merged later: use its final root
        rr, _ = find(r); forced[roots[rr]] = True
    nW1, nW2 = n_rows * 61, n_units * n_rows
    out = {"n_orbits": len(roots), "forced_zero": forced, "n_free": int((~forced).sum()),
           "W1": (orbit[:nW1].reshape(n_rows, 61), sgn[:nW1].reshape(n_rows, 61)),
           "W2": (orbit[nW1:nW1 + nW2].reshape(n_units, n_rows), sgn[nW1:nW1 + nW2].reshape(n_units, n_rows)),
           "Wout": (orbit[nW1 + nW2:], sgn[nW1 + nW2:])}
    return out


def symmetrise(values: np.ndarray, orbit: np.ndarray, sign: np.ndarray, forced_zero: np.ndarray, n_orbits: int) -> np.ndarray:
    """Project an array of coordinates onto the symmetric subspace: each entry becomes sign x (mean over its orbit of sign x value); forced-zero orbits become 0."""
    flat = (values * sign).ravel(); sums = np.bincount(orbit.ravel(), weights=flat, minlength=n_orbits); counts = np.bincount(orbit.ravel(), minlength=n_orbits)
    means = np.where(counts > 0, sums / np.maximum(counts, 1), 0.0); means[forced_zero] = 0.0
    return (means[orbit] * sign).reshape(values.shape)
